-- Caddeden: CANLI (kaynak) veritabanının şemasını yeniden çalıştırılabilir SQL olarak üretir.
--
-- NEDEN VAR: supabase/migrations altındaki dosyalar yalnızca "ek" değişikliklerdir. Temel tablolar
-- (user_profiles, businesses, orders, ...), feedback_write/feedback_read gibi fonksiyonlar ve ilk
-- RLS politikaları OnSpace Cloud veritabanında oluşturulmuştu ve depoda YOKTUR. Bu betik onları
-- tahmin etmek yerine canlı veritabanından birebir okur.
--
-- GÜVENLİK: Yalnızca SELECT çalıştırır (salt okunur). Hiçbir veri, anahtar, parola, app_config değeri
-- veya kullanıcı bilgisi ÇIKTIYA YAZILMAZ. Yalnızca şema (tablo/fonksiyon/politika/bucket tanımı) ve
-- tablo başına satır sayısı (yorum olarak) üretilir.
--
-- KULLANIM (supabase/README.md içinde ayrıntılı):
--   psql "$KAYNAK_DB_URL" -X -q -A -t -f supabase/export/export_live_schema.sql -o live_schema.sql
-- ya da SQL editöründe önce `set search_path = pg_catalog;` çalıştırıp ardından aşağıdaki SELECT'i
-- çalıştırın ve tek hücrelik "script" sonucunu live_schema.sql olarak kaydedin.

set search_path = pg_catalog;

with
pub_tables as (
  select c.oid, c.relname
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
    and not exists (select 1 from pg_depend x where x.objid = c.oid and x.deptype = 'e')
),
parts(s, o, k, ddl) as (

  -- 0: bilgi (uygulanmaz)
  select 0, 0, 'header',
         '-- Üretildi: ' || now()::text || E'\n-- PostgreSQL: ' || version()
         || E'\nset check_function_bodies = off;'
  union all
  select 0, 1, e.extname,
         format('-- extension: %s (şema: %s, sürüm: %s)  -- Supabase panelinden etkinleştirin; bu satır uygulanmaz.',
                e.extname, n.nspname, e.extversion)
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'

  -- 10: enum türleri
  union all
  select 10, 0, t.typname,
         format('do $x$ begin create type %s as enum (%s); exception when duplicate_object then null; end $x$;',
                t.oid::regtype,
                (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder) from pg_enum where enumtypid = t.oid))
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'

  -- 20: bağımsız sequence'ler (identity olmayanlar)
  union all
  select 20, 0, c.relname, format('create sequence if not exists %s;', c.oid::regclass)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')

  -- 30: tablolar (public'e referans veren varsayılanlar 45'e ertelenir)
  union all
  select 30, 0, t.relname,
    format(E'create table if not exists %s (\n%s\n);', t.oid::regclass,
      (select string_agg(
          format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
            case when a.attidentity = 'a' then ' generated always as identity'
                 when a.attidentity = 'd' then ' generated by default as identity' else '' end,
            case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                 when d.adbin is not null and a.attidentity not in ('a', 'd')
                      and pg_get_expr(d.adbin, d.adrelid) !~ 'public\.'
                   then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
            case when a.attnotnull then ' not null' else '' end),
          E',\n' order by a.attnum)
       from pg_attribute a
       left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
       where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from pub_tables t

  -- 40: fonksiyonlar/prosedürler + yürütme yetkileri
  union all
  select 40, 0, p.proname || '/' || p.oid::text, pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend x where x.objid = p.oid and x.deptype = 'e')
  union all
  select 40, 1, p.proname || '/' || p.oid::text,
    format('revoke all on %s %s from public, anon, authenticated, service_role;',
           case p.prokind when 'p' then 'procedure' else 'function' end, p.oid::regprocedure)
    || coalesce((select string_agg(
         format(E'\ngrant execute on %s %s to %s;',
                case p.prokind when 'p' then 'procedure' else 'function' end, p.oid::regprocedure,
                case when x.grantee = 0 then 'public' else quote_ident(r.rolname) end), '')
       from aclexplode(p.proacl) x left join pg_roles r on r.oid = x.grantee
       where x.privilege_type = 'EXECUTE' and (x.grantee = 0 or r.rolname in ('anon', 'authenticated', 'service_role'))), '')
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p') and p.proacl is not null
    and not exists (select 1 from pg_depend x where x.objid = p.oid and x.deptype = 'e')

  -- 45: ertelenmiş varsayılanlar (public fonksiyonu kullananlar)
  union all
  select 45, 0, t.relname || '.' || a.attname,
         format('alter table %s alter column %I set default %s;', t.oid::regclass, a.attname, pg_get_expr(d.adbin, d.adrelid))
  from pub_tables t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where a.attidentity not in ('a', 'd') and a.attgenerated <> 's' and pg_get_expr(d.adbin, d.adrelid) ~ 'public\.'

  -- 50: birincil/benzersiz/check kısıtları, 55: yabancı anahtarlar
  union all
  select case when c.contype = 'f' then 55 else 50 end,
         case c.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'x' then 4 else 1 end,
         t.relname || '.' || c.conname,
         format('alter table only %s add constraint %I %s;', t.oid::regclass, c.conname, pg_get_constraintdef(c.oid))
  from pg_constraint c join pub_tables t on t.oid = c.conrelid
  where c.contype in ('p', 'u', 'c', 'f', 'x')

  -- 60: kısıt dışı indeksler
  union all
  select 60, 0, i.indexrelid::regclass::text,
         regexp_replace(pg_get_indexdef(i.indexrelid), '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || ';'
  from pg_index i join pub_tables t on t.oid = i.indrelid
  where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid)

  -- 70: görünümler
  union all
  select 70, 0, c.relname,
         format('create or replace view %s as %s', c.oid::regclass, pg_get_viewdef(c.oid, true))
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
    and not exists (select 1 from pg_depend x where x.objid = c.oid and x.deptype = 'e')

  -- 75: tetikleyiciler (public tabloları + auth.users)
  union all
  select 75, 0, tg.tgrelid::regclass::text || '.' || tg.tgname,
         pg_get_triggerdef(tg.oid, true) || ';'
         || case when tg.tgenabled = 'D' then format(E'\nalter table %s disable trigger %I;', tg.tgrelid::regclass, tg.tgname) else '' end
  from pg_trigger tg join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where not tg.tgisinternal
    and ((n.nspname = 'public' and c.relkind = 'r') or (n.nspname = 'auth' and c.relname = 'users'))

  -- 80: satır düzeyi güvenlik (RLS)
  union all
  select 80, 0, t.relname,
         format('alter table %s enable row level security;', t.oid::regclass)
         || case when c.relforcerowsecurity then format(E'\nalter table %s force row level security;', t.oid::regclass) else '' end
  from pub_tables t join pg_class c on c.oid = t.oid
  where c.relrowsecurity

  -- 85: politikalar (public tabloları + storage.objects)
  union all
  select 85, 0, p.polrelid::regclass::text || '.' || p.polname,
    format('drop policy if exists %I on %s;', p.polname, p.polrelid::regclass)
    || format(E'\ncreate policy %I on %s as %s for %s to %s%s%s;',
         p.polname, p.polrelid::regclass,
         case when p.polpermissive then 'permissive' else 'restrictive' end,
         case p.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
         case when p.polroles = '{0}'::oid[] then 'public'
              else (select string_agg(quote_ident(r.rolname), ', ' order by r.rolname) from pg_roles r where r.oid = any (p.polroles)) end,
         coalesce(E'\n  using (' || pg_get_expr(p.polqual, p.polrelid) || ')', ''),
         coalesce(E'\n  with check (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')', ''))
  from pg_policy p
  where p.polrelid in (select oid from pub_tables)
     or p.polrelid = 'storage.objects'::regclass

  -- 90: tablo ve sütun yetkileri (yalnızca anon/authenticated/service_role)
  union all
  select 90, 0, t.relname,
    format('revoke all on table %s from anon, authenticated, service_role;', t.oid::regclass)
    || coalesce((select string_agg(format(E'\ngrant %s on table %s to %s;', g.privs, t.oid::regclass, g.rolname), '')
       from (select r.rolname, string_agg(x.privilege_type, ', ' order by x.privilege_type) privs
             from aclexplode(c.relacl) x join pg_roles r on r.oid = x.grantee
             where r.rolname in ('anon', 'authenticated', 'service_role')
             group by r.rolname) g), '')
  from pub_tables t join pg_class c on c.oid = t.oid
  where c.relacl is not null
  union all
  select 90, 1, t.relname || '.' || a.attname,
         format('grant %s (%I) on table %s to %s;', x.privilege_type, a.attname, t.oid::regclass, r.rolname)
  from pub_tables t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped and a.attacl is not null
  cross join lateral aclexplode(a.attacl) x
  join pg_roles r on r.oid = x.grantee
  where r.rolname in ('anon', 'authenticated', 'service_role')

  -- 95: storage bucket tanımları (dosyalar DEĞİL)
  union all
  select 95, 0, b.id,
         format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %L, %L::text[]) '
                || 'on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, '
                || 'allowed_mime_types = excluded.allowed_mime_types;',
                b.id, b.name, b.public, b.file_size_limit, b.allowed_mime_types::text)
  from storage.buckets b

  -- 96: Realtime yayını
  union all
  select 96, 0, pt.tablename,
         format('do $x$ begin alter publication supabase_realtime add table %I.%I; exception when duplicate_object then null; end $x$;',
                pt.schemaname, pt.tablename)
  from pg_publication_tables pt where pt.pubname = 'supabase_realtime'

  -- 99: satır sayıları (yalnızca yorum; geçiş sonrası karşılaştırma için)
  union all
  select 99, 0, t.relname,
         format('-- rowcount %s = %s', t.oid::regclass,
                (xpath('/row/c/text()', query_to_xml(format('select count(*) as c from %s', t.oid::regclass), false, true, '')))[1]::text)
  from pub_tables t
  union all
  select 99, 1, 'auth.users',
         format('-- rowcount auth.users = %s',
                (xpath('/row/c/text()', query_to_xml('select count(*) as c from auth.users', false, true, '')))[1]::text)
  union all
  select 99, 2, 'storage.objects',
         format('-- rowcount storage.objects = %s',
                (xpath('/row/c/text()', query_to_xml('select count(*) as c from storage.objects', false, true, '')))[1]::text)
)
select string_agg(ddl, E'\n\n' order by s, o, k) as script from parts;
